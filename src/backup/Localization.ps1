    param([string]$Language='en')
    $property=$script:PitrBackupLabelData.PSObject.Properties[$Language]
    if($null -eq $property) { $property=$script:PitrBackupLabelData.PSObject.Properties['en'] }
    $labels=@{}
    foreach($entry in $property.Value.PSObject.Properties) { $labels[$entry.Name]=[string]$entry.Value }
    return $labels
}
